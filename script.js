  /* ---------------- Әмбебап drag & drop (mouse + touch + keyboard) ------- */
  function attachDrag(node, opts) {
    var sx = 0, sy = 0, active = false, moved = false, ghost = null, pid = null;
    var lastHover = null;

    function makeGhost(e) {
      var r = node.getBoundingClientRect();
      ghost = node.cloneNode(true);
      ghost.classList.add('drag-ghost');
      ghost.classList.remove('selected');
      ghost.style.width = r.width + 'px';
      ghost.removeAttribute('id');
      document.body.appendChild(ghost);
      moveGhost(e);
    }
    function moveGhost(e) {
      if (!ghost) { return; }
      ghost.style.left = e.clientX + 'px';
      ghost.style.top = e.clientY + 'px';
    }
    function removeGhost() {
      if (ghost && ghost.parentNode) { ghost.parentNode.removeChild(ghost); }
      ghost = null;
    }
    function targetAt(x, y) {
      var el = null;
      try { el = document.elementFromPoint(x, y); } catch (e) { el = null; }
      if (!el) { return null; }
      return el.closest ? el.closest(opts.targetSelector) : null;
    }
    function highlight(x, y) {
      var t = targetAt(x, y);
      if (t !== lastHover) {
        if (lastHover) { lastHover.classList.remove('hover'); }
        lastHover = t;
        if (lastHover) { lastHover.classList.add('hover'); }
      }
    }
    function clearHover() {
      if (lastHover) { lastHover.classList.remove('hover'); lastHover = null; }
    }

    node.addEventListener('pointerdown', function (e) {
      if (node.disabled || node.classList.contains('placed')) { return; }
      if (e.pointerType === 'mouse' && e.button !== 0) { return; }
      active = true; moved = false; sx = e.clientX; sy = e.clientY; pid = e.pointerId;
      try { node.setPointerCapture(pid); } catch (err) { /* ignore */ }
    });

    node.addEventListener('pointermove', function (e) {
      if (!active) { return; }
      if (!moved) {
        if (Math.abs(e.clientX - sx) < 9 && Math.abs(e.clientY - sy) < 9) { return; }
        moved = true;
        node.classList.add('dragging');
        makeGhost(e);
      }
      moveGhost(e);
      highlight(e.clientX, e.clientY);
      if (e.cancelable) { try { e.preventDefault(); } catch (err) { /* ignore */ } }
    });

    function end(e, cancelled) {
      if (!active) { return; }
      active = false;
      clearHover();
      removeGhost();
      node.classList.remove('dragging');
      try { if (pid !== null) { node.releasePointerCapture(pid); } } catch (err) { /* ignore */ }
      if (cancelled) { return; }
      if (moved) {
        var t = targetAt(e.clientX, e.clientY);
        if (typeof opts.onDrop === 'function') { opts.onDrop(t, e); }
      } else if (typeof opts.onTap === 'function') {
        opts.onTap(node, e);
      }
      pid = null;
    }

    node.addEventListener('pointerup', function (e) { end(e, false); });
    node.addEventListener('pointercancel', function (e) { end(e, true); });

    /* пернетақта арқылы таңдау */
    node.addEventListener('click', function (e) {
      if (e.detail === 0 && typeof opts.onTap === 'function') { opts.onTap(node, e); }
    });
    node.addEventListener('keydown', function (e) {
      if (e.key === 'Enter' || e.key === ' ' || e.key === 'Spacebar') {
        e.preventDefault();
        if (typeof opts.onTap === 'function') { opts.onTap(node, e); }
      }
    });
  }

