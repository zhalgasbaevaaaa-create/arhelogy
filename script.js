  /* ----- Level 5 көмекші: тапсырманы аяқтау / құлату ----- */
  function l5Controller(t, idx, host) {
    var fails = 0;
    var resolved = false;

    function next() {
      Timer.hide();
      laterForLevel(function () {
        if (state.hearts <= 0 || state.gameOver) { return; }
        var h = $('#level-body');
        if (!h) { return; }
        h.innerHTML = '';
        renderLevel5(h);
        checkLevelDone(5, 'l5answers');
      }, 900);
    }

    function penalty() {
      if (resolved) { return; }
      fails++;
      state.mistakes++;
      addScore(-2);
      Sound.play('bad');
      if (fails >= 3) { fail(); }
    }

    function fail() {
      if (resolved) { return; }
      resolved = true;
      Timer.hide();
      markTaskAnswered('l5answers', idx, 'bad');
      loseHeart();
      openModal({
        emoji: '💡',
        title: 'ТАПСЫРМА ОРЫНДАЛМАДЫ',
        body:
          '<p class="fb-text">−2 ұпай және бір мүмкіндік жоғалды.</p>' +
          '<div class="fb-tip" style="margin-top:10px"><b>💡 АРХЕОЛОГТЫҢ КЕҢЕСІ</b><br>' + esc(t.explain) + '</div>',
        actions: [{ label: 'ЖАЛҒАСТЫРУ ▶', cls: 'btn-gold', onClick: function () { next(); } }]
      });
      if (state.hearts <= 0) { next = function () {}; }
    }

    function success() {
      if (resolved) { return; }
      resolved = true;
      Timer.hide();
      addScore(10);
      Sound.play('found');
      markTaskAnswered('l5answers', idx, 'ok');
      toast('Тапсырма орындалды! +10 ұпай', 'gold', '🏆', 2000);
      checkLevelDone(5, 'l5answers');
      next();
    }

    return { penalty: penalty, fail: fail, success: success, isResolved: function () { return resolved; } };
  }

