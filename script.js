  var Confetti = (function () {
    var canvas = $('#confetti');
    var ctx = null;
    var parts = [];
    var raf = null;
    var running = false;
    var colors = ['#f2c76c', '#d9a441', '#b07a3a', '#fbf4e6', '#7a5733', '#a8412f', '#3f7d3a'];

    if (canvas) {
      try { ctx = canvas.getContext('2d'); } catch (e) { ctx = null; }
    }

    function size() {
      if (!canvas) { return; }
      var dpr = Math.min(window.devicePixelRatio || 1, 2);
      canvas.width = Math.max(1, Math.floor(window.innerWidth * dpr));
      canvas.height = Math.max(1, Math.floor(window.innerHeight * dpr));
      if (ctx) { ctx.setTransform(dpr, 0, 0, dpr, 0, 0); }
    }

    function frame() {
      if (!ctx) { running = false; return; }
      ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);
      var w = window.innerWidth;
      for (var i = parts.length - 1; i >= 0; i--) {
        var p = parts[i];
        p.vy += p.g;
        p.x += p.vx;
        p.y += p.vy;
        p.rot += p.vr;
        p.life -= 1;
        if (p.life <= 0 || p.y > window.innerHeight + 40) { parts.splice(i, 1); continue; }
        ctx.save();
        ctx.translate(p.x, p.y);
        ctx.rotate(p.rot);
        ctx.globalAlpha = clamp(p.life / 60, 0, 1);
        ctx.fillStyle = p.color;
        if (p.round) {
          ctx.beginPath(); ctx.arc(0, 0, p.w / 2, 0, Math.PI * 2); ctx.fill();
        } else {
          ctx.fillRect(-p.w / 2, -p.h / 2, p.w, p.h);
        }
        ctx.restore();
        if (p.x < -60 || p.x > w + 60) { parts.splice(i, 1); }
      }
      if (parts.length) {
        raf = window.requestAnimationFrame(frame);
      } else {
        running = false;
        ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);
      }
    }

    function burst(count) {
      if (!ctx || prefersReducedMotion()) { return; }
      size();
      var n = count || 130;
      var w = window.innerWidth;
      for (var i = 0; i < n; i++) {
        parts.push({
          x: w * (0.15 + Math.random() * 0.7),
          y: -20 - Math.random() * window.innerHeight * 0.35,
          vx: (Math.random() - 0.5) * 3.2,
          vy: 1.6 + Math.random() * 3.4,
          g: 0.045 + Math.random() * 0.05,
          w: 5 + Math.random() * 8,
          h: 7 + Math.random() * 11,
          rot: Math.random() * Math.PI,
          vr: (Math.random() - 0.5) * 0.22,
          color: pick(colors),
          round: Math.random() < 0.25,
          life: 150 + randInt(90)
        });
      }
      if (!running) { running = true; raf = window.requestAnimationFrame(frame); }
    }

    function stop() {
      parts = [];
      if (raf) { window.cancelAnimationFrame(raf); raf = null; }
      running = false;
      if (ctx) { ctx.clearRect(0, 0, window.innerWidth, window.innerHeight); }
    }

    window.addEventListener('resize', function () { if (running) { size(); } });

    return { burst: burst, stop: stop };
  })();

