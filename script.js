  function startNewGame(silentToast) {
    state = defaultState();
    state.started = true;
    state.cells = buildCells();
    save();
    updateHUD(false);
    updateStartButtons();
    if (!silentToast) { toast('Экспедиция басталды! Сәттілік, зерттеуші!', 'gold', '⛏️', 2400); }
  }

  function resetAll() {
    Timer.hide();
    Confetti.stop();
    closeModal();
    storage.del(SAVE_KEY);
    state = defaultState();
    updateHUD(false);
    updateStartButtons();
    showScreen('screen-start');
    toast('Барлық прогресс тазаланды. Жаңа экспедицияға дайын болыңыз!', '', '🔄', 2600);
  }

  function updateStartButtons() {
    var cont = $('#btn-continue');
    if (!cont) { return; }
    var saved = !!storage.get(SAVE_KEY);
    var inProgress = saved && state.started && !state.finished && !state.gameOver && state.hearts > 0;
    if (inProgress) {
      cont.hidden = false;
      cont.innerHTML = '<span aria-hidden="true">⏳</span> ОЙЫНДЫ ЖАЛҒАСТЫРУ';
    } else if (saved && state.finished) {
      cont.hidden = false;
      cont.innerHTML = '<span aria-hidden="true">🏆</span> НӘТИЖЕНІ КӨРУ';
    } else {
      cont.hidden = true;
    }
  }

  function continueGame() {
    Sound.unlock();
    Sound.play('click');
    if (state.finished) { showFinal(); return; }
    if (state.hearts <= 0) { gameOver(); return; }
    showScreen(state.level > 0 ? 'screen-game' : 'screen-expedition');
    if (state.level > 0) { renderLevel(state.level); }
    else { state.level = 1; save(); openLevel(state.unlockedLevel); }
    toast('Экспедиция жалғасуда: LEVEL ' + Math.max(1, state.level), 'good', '▶', 2000);
  }

