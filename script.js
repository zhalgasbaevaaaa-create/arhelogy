  var Timer = (function () {
    var id = null;
    var left = 0;
    var total = 0;
    var onEnd = null;
    var paused = false;
    var box = $('#timer-box');
    var val = $('#timer-val');
    var sr = $('#timer-sr');

    function paint() {
      if (val) { val.textContent = String(Math.max(0, left)); }
      if (box) { box.classList.toggle('warn', left <= 5); }
      if (sr) { sr.textContent = left + ' секунд қалды'; }
    }
    function tick() {
      if (paused) { return; }
      left--;
      paint();
      if (left <= 5 && left > 0) { Sound.play('tick'); }
      if (left <= 0) {
        var f = onEnd;      /* stop() onEnd-ті тазалайды — сондықтан алдын ала сақтаймыз */
        stop();
        if (typeof f === 'function') { f(); }
      }
    }
    function stop() {
      if (id) { window.clearInterval(id); id = null; }
      onEnd = null;
    }
    function hide() {
      stop();
      if (box) { box.hidden = true; }
      if (sr) { sr.textContent = ''; }
    }
    function start(sec, cb) {
      stop();
      if (!box) { return; }
      total = sec; left = sec; onEnd = cb || null; paused = false;
      box.hidden = false;
      paint();
      id = window.setInterval(tick, 1000);
    }
    document.addEventListener('visibilitychange', function () {
      if (!id) { return; }
      paused = document.hidden;
    });
    return { start: start, stop: stop, hide: hide, restart: function () { if (total) { start(total, onEnd); } } };
  })();

