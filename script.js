  function load() {
    var raw = storage.get(SAVE_KEY);
    if (!raw) { return null; }
    var data;
    try { data = JSON.parse(raw); } catch (e) { return null; }
    if (!data || typeof data !== 'object' || data.v !== SAVE_VERSION) { return null; }
    var base = defaultState();
    var s = {};
    for (var k in base) {
      if (Object.prototype.hasOwnProperty.call(base, k)) { s[k] = base[k]; }
    }
    for (var key in data) {
      if (Object.prototype.hasOwnProperty.call(base, key)) { s[key] = data[key]; }
    }
    /* типтерді тексеру */
    if (typeof s.score !== 'number' || s.score < 0) { s.score = 0; }
    if (typeof s.hearts !== 'number') { s.hearts = HEARTS_MAX; }
    s.hearts = clamp(Math.floor(s.hearts), 0, HEARTS_MAX);
    if (!Array.isArray(s.artifacts)) { s.artifacts = []; }
    s.artifacts = s.artifacts.filter(function (id) { return !!artifactById(id); });
    if (!Array.isArray(s.completedLevels)) { s.completedLevels = []; }
    s.completedLevels = s.completedLevels.filter(function (n) { return n >= 1 && n <= 5; });
    s.unlockedLevel = clamp(parseInt(s.unlockedLevel, 10) || 1, 1, 5);
    s.level = clamp(parseInt(s.level, 10) || 0, 0, 5);
    if (typeof s.mistakes !== 'number' || s.mistakes < 0) { s.mistakes = 0; }
    if (typeof s.scans !== 'number') { s.scans = SCANS_MAX; }
    s.scans = clamp(Math.floor(s.scans), 0, SCANS_MAX);
    ['l2answers', 'l3answers', 'l4answers', 'l4analysis', 'l5answers'].forEach(function (kk) {
      if (!s[kk] || typeof s[kk] !== 'object' || Array.isArray(s[kk])) { s[kk] = {}; }
    });
    if (!s.cells || !Array.isArray(s.cells) || s.cells.length !== DIG_COLS_ROWS) { s.cells = null; }
    return s;
  }

